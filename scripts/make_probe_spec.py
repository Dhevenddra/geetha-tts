r"""Write the job spec for ``m0-selfdelete-probe`` (proposal R5).

    py -3.11 scripts\make_probe_spec.py

The question this probe answers
-------------------------------
The entire GPU safety design rests on a pod being able to delete *itself*. RunPod
injects ``RUNPOD_POD_ID`` and a pod-scoped ``RUNPOD_API_KEY`` into every pod, and
**whether that scoped key may delete its own pod is documented nowhere.** If it may
not, then ``ops/wrapper.py``'s deadline and idle watchdog both end in a no-op and the
only thing standing between us and a runaway pod is the PC-side watchdog — which
cannot help if the PC is asleep.

Proposal R5 says: answer that for a few rupees before any real money rides on it. So
this spec runs the probe from ``ops.wrapper.build_probe_command`` — the same teardown
snippet the real wrapper uses, not a copy — on the cheapest GPU for a few minutes.

Why it is filed under M1 rather than getting its own gate
---------------------------------------------------------
The runbook gives the probe its own burn-tracker row but there is no gate M0, and
``JobSpec`` refuses a gate outside M1-M6 on purpose. Inventing one would mean touching
the gate budgets, which are a decision the operator made (D-013). Filing the probe
under **M1** instead costs about INR 10 of M1's INR 300 and keeps the gate model
intact: the probe is M1's precondition, so spending M1's money on it is honest. It
still gets its own run_id and its own burn-tracker row, so the spend is visible
separately.

This script writes the spec. It does **not** write the burn-tracker row and it does
**not** approve anything: that happens only after the operator's literal "approved"
to ``/gate M1``.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from ops.spec import JobSpec
from ops.wrapper import build_probe_command

SPEC_PATH = Path(__file__).resolve().parent.parent / "ops" / "jobs" / "m0-selfdelete-probe.yaml"

# The probe does no compute at all -- it sleeps, deletes itself and reports -- so the
# GPU choice is purely price per minute, and the cheapest tier is strictly better.
#
# It was originally the RTX 4090 because that is what the training plan uses. Measured
# live on 27 Oct: a price in the catalogue does not mean capacity exists. A minimal
# create was refused with HTTP 500 "There are no instances currently available" for the
# A2000, the 3090 AND the 4090, and accepted for the L4 — so availability is per GPU
# type and volatile, and the payload was never the problem. The L4 is dearer than the
# plan assumed, which is why the probe is shortened to keep the worst case small.
GPU_TYPE = "NVIDIA L4"

# Measured 27 Oct for INR 1.06: the runbook's
# "runpod/pytorch:2.4.0-py3.11-cuda12.4.1-devel-ubuntu22.04" does not exist. RunPod
# accepted the create, failed the pull and destroyed the pod in seven seconds, which
# reads exactly like a capacity failure. Real tags look like the one below; this is a
# stable release (no -rc), CUDA 12.9, torch 2.8, Ubuntu 22.04.
IMAGE = "runpod/pytorch:1.4.1-cu1290-torch280-ubuntu2204"

# 0.15 h at $0.59/h (secure) is about INR 7.8 — the worst case, where the pod cannot delete
# itself and runs until the wrapper's deadline. If the self-delete works, the pod dies
# after about two minutes and costs under INR 2. The ceiling stays at INR 15.
MAX_HOURS = 0.15
MAX_COST_INR = 15.0

SLEEP_SECONDS = 120


def build_spec() -> dict:
    return {
        "run_id": "m0-selfdelete-probe",
        "gate": "M1",
        "provider": "runpod",
        # SECURE, not the cheaper COMMUNITY. Measured 27 Oct: the same L4 create was
        # refused on COMMUNITY and accepted on SECURE minutes apart. For a INR 8 probe,
        # paying 1.3x for capacity that exists is the right trade; real training runs
        # should still prefer COMMUNITY and retry.
        "cloud_type": "SECURE",
        "gpu_type": GPU_TYPE,
        "image": IMAGE,
        "disk_gb": 10,
        "max_hours": MAX_HOURS,
        "max_cost_inr": MAX_COST_INR,
        "command": build_probe_command(SLEEP_SECONDS),
        # Nothing to download and nothing to resume: checkpoint_repo is required by the
        # spec (a run with nowhere to resume from is lost work) and the probe has no
        # work to lose, so it points at the same private repo and writes nothing.
        "data_repos": [],
        "checkpoint_repo": "dhevenddra/geetha-ckpt",
        "wandb_project": "geetha",
    }


def main() -> int:
    spec = build_spec()
    # Validate before writing: a spec on disk that cannot be parsed is worse than none.
    JobSpec.from_dict(spec)

    SPEC_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPEC_PATH.write_text(
        "# Generated by scripts/make_probe_spec.py — regenerate rather than hand-edit,\n"
        "# so the probe keeps using the same teardown code as the real wrapper.\n"
        + yaml.safe_dump(spec, allow_unicode=True, sort_keys=True, width=100),
        encoding="utf-8",
    )
    print(f"wrote {SPEC_PATH}")
    print(f"  {MAX_HOURS:g} h on {GPU_TYPE}, ceiling INR {MAX_COST_INR:.0f}, gate M1")
    print()
    print("Nothing is approved and no burn-tracker row exists, so a launch will refuse.")
    print("Prove that first:")
    print("  py -3.11 -m ops.gpu launch ops/jobs/m0-selfdelete-probe.yaml --check-only")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
