"""Numbers, dates and rupees must reach the model as Tamil words."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

_PATH = Path(__file__).resolve().parents[1] / "release" / "tamil_text.py"
_SPEC = importlib.util.spec_from_file_location("geetha_release_tamil_text", _PATH)
tamil = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(tamil)


