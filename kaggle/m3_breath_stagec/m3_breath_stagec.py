    from inference import TTS, ids_to_codes  # type: ignore

    tts = TTS(local)
    tts.lm = PeftModel.from_pretrained(tts.lm, str(stage_b), adapter_name="stageB")
    tts.lm.load_adapter(str(stage_c), adapter_name="stageC")
    tts.lm.eval()                        # NOT merged (D-049)
    if torch.cuda.get_device_capability(0)[0] < 8:
        tts.lm = tts.lm.half()
    detector = BreathDetector.from_dict(DETECTOR)
    tok, base = tts.tok, tts._base
    start_speech = tok.convert_tokens_to_ids("<|start_of_speech|>")
    stop_ids = sorted({tts._eos, tok.eos_token_id})

    def enc(text: str) -> list[int]:
        return tok.encode(text, add_special_tokens=False)

    def prompt(text: str, speaker: str) -> list[int]:
        return (enc(HEAD) + enc(f"<|speaker>{speaker}<speaker|>\n")
                + enc("<|style>CONV<style|>\n") + enc("<|env>studio<env|>\n")
                + enc(text) + enc(TAIL) + [start_speech])

    def decode(tokens: list[int]) -> np.ndarray:
        try:
            with torch.no_grad():
                codes = ids_to_codes(tokens, base, tts.device)
                wav = tts.vocos(tts.snac.quantizer.from_codes(codes).float())
            return wav[0, 0].clamp(-1, 1).float().cpu().numpy().astype(np.float32).reshape(-1)
        except ValueError:
            return np.zeros(0, dtype=np.float32)

    def generate(ids: list[int], adapter: str, seed: int, temperature: float):
        """The sampler of m2_breath_insert (repetition, frame grammar, top-k, top-p)."""
        tts.lm.set_adapter(adapter)
        torch.manual_seed(seed)
        seen, tokens, past, ended = list(ids), [], None, False
        feed = torch.tensor([ids], device=tts.device)
        with torch.no_grad():
            while len(tokens) < MAX_NEW_TOKENS:
                out = tts.lm(input_ids=feed, past_key_values=past, use_cache=True)
                past = out.past_key_values
                logits = out.logits[0, -1].float()
                index = torch.tensor(sorted(set(seen)), device=logits.device)
                picked = logits[index]
                logits[index] = torch.where(picked < 0, picked * REPETITION, picked / REPETITION)
                position = len(tokens) % FRAME_TOKENS
                allowed = torch.full_like(logits, float("-inf"))
                low = base + position * CODEBOOK
                allowed[low:low + CODEBOOK] = 0.0
                if position == 0 and tokens:
                    allowed[stop_ids] = 0.0
                top = torch.topk((logits + allowed) / temperature, TOP_K)
                probs = torch.softmax(top.values, dim=-1)
                keep = torch.cumsum(probs, dim=-1) - probs < TOP_P
                probs = torch.where(keep, probs, torch.zeros_like(probs))
                token = int(top.indices[torch.multinomial(probs / probs.sum(), 1)])
                if token in stop_ids:
                    ended = True
                    break
                tokens.append(token)
                seen.append(token)
                feed = torch.tensor([[token]], device=tts.device)
        return tokens, ended

