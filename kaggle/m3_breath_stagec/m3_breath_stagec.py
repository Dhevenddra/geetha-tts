def train(token: str, shard_paths: list[Path], stage_b: Path) -> Path:
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    from geetha.text.tokenizer_check import assert_tokenizer
    from geetha.train import stage

    args = stage.parse_args(TRAIN_ARGS)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    shutil.copytree(stage_b, out / "adapter_stageB_final", dirs_exist_ok=True)

    def model_and_tokenizer(_args, _token):
        tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, revision=BASE_REVISION, token=token)
        assert_tokenizer(dict(tokenizer.get_added_vocab()), len(tokenizer))
        native_bf16 = torch.cuda.get_device_capability(0)[0] >= 8
        dtype = torch.bfloat16 if native_bf16 else torch.float16
        log(f"  loading the base in {dtype} on {torch.cuda.get_device_name(0)}")
        model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, revision=BASE_REVISION, token=token, torch_dtype=dtype,
            device_map={"": 0})
        return model, tokenizer

    code = stage.run(args, store=stage.LocalStore(WORK / "store"),
                     model_and_tokenizer=model_and_tokenizer,
                     shards=lambda _a, _t: (shard_paths, []))
    final = out / "adapter_stageC_final"
    result = out / "stageC_result.json"
    if result.exists():
        shutil.copy(result, OUT_DIR / "stageC_result.json")
        log(result.read_text(encoding="utf-8"))
    if code != 0 or not (final / "adapter_config.json").exists():
        raise SystemExit(f"training did not finish cleanly (exit {code})")
    shutil.copytree(final, OUT_DIR / "adapter_stageC_final", dirs_exist_ok=True)
    gc.collect()
    torch.cuda.empty_cache()
    return final


