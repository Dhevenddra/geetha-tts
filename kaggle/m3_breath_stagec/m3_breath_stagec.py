def build_shards(token: str) -> list[Path]:
    """One parquet of generated rows, one of real untagged studio rows."""
    import pyarrow as pa
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download, list_repo_files

    if not SELECTION:
        raise SystemExit("SELECTION is empty: run scripts\\build_breath_rows.py first")
    source = find_dataset("tokens.jsonl") / "tokens.jsonl"
    generated, per_voice = [], {}
    with source.open(encoding="utf-8") as handle:
        for line in handle:
            record = json.loads(line)
            text = SELECTION.get(record["file"])
            if text is None:
                continue
            tokens = record["tokens"]
            if len(tokens) % FRAME_TOKENS or not tokens:
                raise SystemExit(f"{record['file']}: {len(tokens)} tokens is not whole frames")
            generated.append({"source": "selfaug", "shard": "m2_breath_gen",
                              "row_index": len(generated), "speaker": record["voice"],
                              "style": "CONV", "env": "studio", "text": text,
                              "repeat": 1, "tokens": tokens})
            per_voice[record["voice"]] = per_voice.get(record["voice"], 0) + 1
    if len(generated) != len(SELECTION):
        raise SystemExit(f"SELECTION names {len(SELECTION)} clips, tokens.jsonl has "
                         f"{len(generated)} of them")
    log(f"  generated rows: {len(generated)} {per_voice}, tagged "
        f"{sum(BREATH_TAG in r['text'] for r in generated)}")

    names = sorted(n for n in list_repo_files(CODES_B, repo_type="dataset", token=token)
                   if n.endswith(".parquet"))
    stride = max(1, len(names) // STUDIO_SHARDS)
    pool: dict[str, list[dict]] = {}
    for name in names[::stride][:STUDIO_SHARDS]:
        table = pq.read_table(hf_hub_download(CODES_B, name, repo_type="dataset", token=token))
        for row in table.to_pylist():
            if row["speaker"] in per_voice and BREATH_TAG not in row["text"] \
                    and 2.0 <= (row.get("duration_s") or 0.0) <= 12.0:
                pool.setdefault(row["speaker"], []).append(row)
    rng = random.Random(SEED)
    studio = []
    for voice, count in sorted(per_voice.items()):
        rows = pool.get(voice, [])
        wanted = min(len(rows), round(count * STUDIO_PER_GENERATED))
        for row in rng.sample(rows, wanted):
            studio.append({"source": row["source"], "shard": row["shard"],
                           "row_index": row["row_index"], "speaker": row["speaker"],
                           "style": row["style"], "env": row["env"], "text": row["text"],
                           "repeat": 1, "tokens": row["tokens"]})
        log(f"  studio rows for {voice}: {wanted} of {len(rows)} candidates")
    schema = pa.schema([("source", pa.string()), ("shard", pa.string()),
                        ("row_index", pa.int32()), ("speaker", pa.string()),
                        ("style", pa.string()), ("env", pa.string()), ("text", pa.string()),
                        ("repeat", pa.int32()), ("tokens", pa.list_(pa.int32()))])
    folder = WORK / "shards"
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, rows in (("selfaug.parquet", generated), ("studio.parquet", studio)):
        pq.write_table(pa.Table.from_pylist(rows, schema=schema), folder / name)
        paths.append(folder / name)
    return paths


